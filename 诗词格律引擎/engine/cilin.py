def bu_of(group: str, yun: str) -> tuple[int, ...]:
    """返回 (声部, 韵目) 对应的词林正韵候选部；未知返回空元组。"""
    cls = GROUP_TO_CLASS.get(group)
    if not cls:
        return ()
    return CILIN.get(cls, {}).get(yun, ())


def is_half(yun: str) -> bool:
    return yun in HALF_RHYMES


def validate() -> list[str]:
    """自检：19 部是否连续、声调类是否齐全、韵目数是否为 106。"""
    problems = []
    all_bu = {b for table in CILIN.values() for bs in table.values() for b in bs}
    if all_bu != set(range(1, 20)):
        problems.append(f"部号不连续：{sorted(all_bu)}")
    n = sum(len(t) for t in CILIN.values())
    if n != 106:
        problems.append(f"韵目数应为 106，实为 {n}")
    for cls in ("平", "上", "去", "入"):
        if cls not in CILIN:
            problems.append(f"缺声调类：{cls}")
    for b in range(1, 20):
        if b not in BU_SIZE_NOTE:
            problems.append(f"部 {b} 缺说明")
    return problems


