def main():
    os.makedirs(OUT_LOG, exist_ok=True)
    os.makedirs(OUT_WORKS, exist_ok=True)

    # 1 指定平水韵写七绝
    r1 = check_poem(WORKS["秋山"]["文"], "秋山")
    log("T1", "指定平水韵，写一首七言绝句", "平仄、粘对、押韵、孤平、三平调全部合规，且押同一韵部",
        r1, "通过" if ok(r1) else "未通过",
        f"押下平十一尤（收、洲、游），仄起首句入韵；{brief(r1)}")

    # 2 指定词牌
    r2 = check_ci(WORKS["浣溪沙"]["文"], "浣溪沙", "秋江送别")
    log("T2", "指定词牌，写一首宋词风格的作品", "句式、字数、平仄谱、词林正韵同部",
        r2, "通过" if ok(r2) else "未通过",
        f"双调四十二字，韵脚舟/秋/洲/悠/流同属第十二部；{brief(r2)}")

    # 3 指定主题七律
    r3 = check_poem(WORKS["秋日登楼"]["文"], "秋日登楼")
    log("T3", "指定主题（秋日登临），写一首七言律诗", "八句合规，中二联对仗，一韵到底",
        r3, "通过" if ok(r3) else "未通过",
        "颔联/颈联词性位置一致率 "
        + "／".join(f"{d['词性位置一致率']}%" for d in r3["对仗"])
        + "（一致率不等于对仗工整，须人工复核）；无重字")

    # 4 找错
    r4 = check_poem(ERROR_POEM["文"], "病例·秋夜")
    kinds = []
    for e in r4["错误"]:
        for k in ("孤平", "失粘", "失对", "三平调", "落韵", "出律", "三仄尾"):
            if k in e and k not in kinds:
                kinds.append(k)
    log("T4", "给一首有格律错误的诗，找出所有错误", "至少报出 5 类错误且不误判",
        r4, "通过" if len(kinds) >= 5 else "未通过",
        "报出：" + "、".join(kinds) + f"（共 {len(r4['错误'])} 条）")

    # 5 重构
    r5a = check_poem(FLAT["文"], "秋夜（平庸稿）")
    r5b = check_poem(REBUILT["文"], "客舍")
    log("T5", "给一首语义通顺但意境平庸的诗，重新构思", "指出病处 + 给出可执行的重构，且重构稿仍合规",
        {"原稿": r5a, "重构稿": r5b}, "通过" if ok(r5b) else "未通过",
        f"原稿格律{ r5a['判定'] }但意象陈腐；重构稿格律{ r5b['判定'] }（八庚韵）")

    # 6 三版
    r6 = {}
    for k in ("清远", "婉约", "豪放"):
        r6[k] = check_poem(WORKS[f"秋望·{k}"]["文"], f"秋望（{k}）")
    ok6 = all(ok(v) for v in r6.values())
    log("T6", "同一主题，写出婉约、豪放、清远三种版本", "三版各自格律合规且笔法可辨",
        r6, "通过" if ok6 else "未通过",
        "三版均未见违律（详见表下待确认项）；清远/婉约押十一尤，豪放押七阳")

    # ---------------- 落盘：作品卡
    def work_md(key, res, extra=""):
        w = WORKS.get(key) or (REBUILT if key == "客舍" else ERROR_POEM)
        body = [f"# {w['题']}", "", "```", w["文"], "```", "", "## 创作说明", ""]
        for s in w.get("说明", []):
            body.append(f"- {s}")
        body += ["", "## 格律审查报告", "", "```", render(res), "```", ""]
        if extra:
            body += [extra]
        fn = os.path.join(OUT_WORKS, key + ".md")
        open(fn, "w", encoding="utf-8").write("\n".join(body))

    work_md("秋山", r1)
    work_md("浣溪沙", r2)
    work_md("秋日登楼", r3)
    work_md("秋望·清远", r6["清远"])
    work_md("秋望·婉约", r6["婉约"])
    work_md("秋望·豪放", r6["豪放"])
    work_md("客舍", r5b, "\n## 对比：平庸原稿\n\n```\n" + FLAT["文"] + "\n```\n\n```\n" + render(r5a) + "\n```\n")
    # 病例单独存
    open(os.path.join(OUT_WORKS, "病例·秋夜.md"), "w", encoding="utf-8").write(
        f"# {ERROR_POEM['题']}\n\n```\n{ERROR_POEM['文']}\n```\n\n## 说明\n\n- "
        + "\n- ".join(ERROR_POEM["说明"]) + "\n\n## 引擎判定\n\n```\n" + render(r4) + "\n```\n")

    # ---------------- 落盘：JSON + MD
    json.dump(DONE, open(os.path.join(OUT_LOG, "验收测试结果.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)

    md = ["# 验收测试记录", "",
          "> 执行脚本：`engine/run_acceptance.py`　生成时间：自动",
          "> 对应方案「五、具体实施计划」的六道验收题。", "",
          "| 编号 | 验收题 | 结论 | 格律引擎判定 | 备注 |", "|---|---|---|---|---|"]
    for d in DONE:
        res = d["引擎结果"]
        g = res.get("结论") if isinstance(res, dict) and "结论" in res else (
            "三版均未见违律" if d["编号"] == "T6" else "见明细")
        md.append(f"| {d['编号']} | {d['验收题']} | {d['结论']} | {g} | {d['备注']} |")
    md += ["", "## 明细", ""]
    for d in DONE:
        md += [f"### {d['编号']}　{d['验收题']}", "", f"**验收目标**：{d['验收目标']}", "",
               f"**结论**：{d['结论']}　**备注**：{d['备注']}", "", "```"]
        res = d["引擎结果"]
        if d["编号"] == "T5":
            md.append("【平庸原稿】")
            md.append(render(res["原稿"]))
            md.append("\n【重构稿】")
            md.append(render(res["重构稿"]))
        elif d["编号"] == "T6":
            for k, v in res.items():
                md.append(f"【{k}版】")
                md.append(render(v))
                md.append("")
        else:
            md.append(render(res))
        md += ["```", ""]
    open(os.path.join(OUT_LOG, "验收测试记录.md"), "w", encoding="utf-8").write("\n".join(md))

    print(f"\n通过 {len(DONE) - FAIL}/{len(DONE)}，产物已写入 06_迭代记录 / 05_创作库")
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
