import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gedou import check_poem, check_ci, render, is_ok  # noqa: E402

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KB = os.path.join(BASE, "诗歌知识库")
OUT_LOG = os.path.join(KB, "06_迭代记录")
OUT_WORKS = os.path.join(KB, "05_创作库")

DONE = []
FAIL = 0


def ok(res) -> bool:
    """无明确违律即可接受；待人工确认项会在备注中如实列出。"""
    return is_ok(res)


def brief(res) -> str:
    """把判定码与待确认数压成一行，写进验收记录。"""
    return f"{res.get('判定', '-')}／待确认 {len(res.get('待确认', []))} 处"


def log(tid, name, target, res, verdict, note=""):
    global FAIL
    ok = verdict == "通过"
    if not ok:
        FAIL += 1
    DONE.append({"编号": tid, "验收题": name, "验收目标": target, "结论": verdict,
                 "备注": note, "引擎结果": res})
    flag = "✅" if ok else "❌"
    print(f"{flag} {tid} {name} —— {verdict}  (格律：{res.get('结论', '-')})")


