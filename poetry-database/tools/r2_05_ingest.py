def build_coverage(con):
    rows = dump.load()
    con.execute("DELETE FROM reading_records_r2_05")
    n_read = n_other = 0
    for key, status, sd, st, exc, nf in UNITS:
        hit = dump.resolve(con, key)
        if not hit:
            print(f"  [warn] 未找到单元 {key}")
            continue
        uid, pc, vol, num, title, pp, a, b, lv = hit[0]
        total = sum(len(re.findall(r"[\u4e00-\u9fff]", rows.get(p, ""))) for p in range(a, b + 1))
        read = total if status == "READ" else 0
        cov = round(read / total, 4) if total else 0.0
        gate = 1 if (status == "READ" and cov >= 1.0 and sd == st) else 0
        con.execute("INSERT INTO reading_records_r2_05 VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,datetime('now'))",
                    (key, "wangli_shicilv", pc, f"{num} {title}", a, b,
                     a - 8, b - 8, total, read, cov, sd, st, status, gate, exc, nf))
        # 同时更新 reading_units（章级）
        if lv == 1:
            con.execute("UPDATE reading_units SET status=?, note=? WHERE unit_id=?",
                        (status, f"R2-05 全文通读；覆盖 {cov:.0%}；{exc or '无 OCR 异常'}", uid))
        else:
            con.execute("UPDATE reading_units SET status=? WHERE unit_id=?", (status, uid))
        n_read += 1 if status == "READ" else 0
        n_other += 1 if status != "READ" else 0
    # 词学十讲：book_chapters 中 idx=5 为第一讲，idx=14 为第十讲（idx 0–4 为序与目录）
    for idx, status, note in CIXUE:
        t = con.execute("SELECT title, chars FROM book_chapters WHERE book_id='long_cixue_shijiang' AND idx=?",
                        (idx + 4,)).fetchone()
        if not t:
            continue
        total = t[1]
        read = total if status == "READ" else 0
        cov = round(read / total, 4) if total else 0.0
        gate = 1 if status == "READ" and cov >= 1.0 else 0
        con.execute("INSERT INTO reading_records_r2_05 VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,datetime('now'))",
                    (f"E:第{idx}讲", "long_cixue_shijiang", "E", t[0], None, None, None, None,
                     total, read, cov, 1, 1, status, gate, note, "E_词学十讲状态复核.md"))
        n_read += 1 if status == "READ" else 0
        n_other += 1 if status != "READ" else 0
    con.commit()
    print(f"  阅读记录：READ {n_read} 条，非 READ {n_other} 条")


