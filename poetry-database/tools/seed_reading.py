def main() -> int:
    conn = sqlite3.connect(DB)
    conn.execute("DELETE FROM theory_claims")
    conn.execute("DELETE FROM reading_notes")
    conn.execute("DELETE FROM reading_progress")
    conn.executemany(
        "INSERT INTO theory_claims(book_id,page,topic,claim,quote,scope,status,note) "
        "VALUES (?,?,?,?,?,?,?,?)", CLAIMS)
    conn.executemany(
        "INSERT INTO reading_notes(book_id,unit,page_from,page_to,topic,author_view,quote,my_comment,created) "
        "VALUES (?,?,?,?,?,?,?,?,?)",
        [(b, u, pf, pt, t, av, q, mc, TS) for b, u, pf, pt, t, av, q, mc in NOTES])
    conn.executemany("INSERT OR REPLACE INTO reading_progress(book_id,unit,status,ts,note) "
                     "VALUES (?,?,?,?,?)",
                     [(b, u, s, TS, n) for b, u, s, n in PROGRESS])
    conn.commit()
    print(f"theory_claims {len(CLAIMS)} 条；reading_notes {len(NOTES)} 条；reading_progress {len(PROGRESS)} 条")
    conn.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
