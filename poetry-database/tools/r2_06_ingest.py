def load_pages():
    rows = {}
    for line in PAGES.open(encoding="utf-8"):
        if line.strip():
            r = json.loads(line)
            rows[int(r["page"])] = r["text"]
    return rows


def han(t):
    return len(re.findall(r"[\u4e00-\u9fff]", t))


