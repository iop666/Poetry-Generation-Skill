def quote_from_evidence(code: int, pdf_from: int) -> str:
    files = sorted((EVID / "chapters").glob(f"{code}_{pdf_from:03d}_*.md"))
    if not files:
        return ""
    txt = files[0].read_text(encoding="utf-8")
    quotes = [l[2:].strip() for l in txt.splitlines() if l.startswith("> ")]
    return quotes[0][:220] if quotes else ""


